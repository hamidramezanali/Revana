"""Generate serialized response model types from the backend's OpenAPI schemas."""

import json
import sys
from pathlib import Path

from app.main import app

TARGET = Path(__file__).resolve().parents[2] / "frontend" / "src" / "api.generated.ts"


def name(value: str) -> str:
    return "Api" + value.replace("-", "_")


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return name(schema["$ref"].rsplit("/", 1)[1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            separator = " & " if key == "allOf" else " | "
            return "(" + separator.join(typescript(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object" or "properties" in schema:
        # Pydantic serializes defaulted response fields too (no exclude_unset routes).
        fields = [
            f"{json.dumps(key)}: {typescript(value)}"
            for key, value in schema.get("properties", {}).items()
        ]
        return "{ " + "; ".join(fields) + " }"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def render() -> str:
    schemas = app.openapi()["components"]["schemas"]
    return (
        "// Generated by backend/scripts/export_client_types.py. Do not edit.\n"
        + "\n".join(
            f"export type {name(key)} = {typescript(value)};"
            for key, value in sorted(schemas.items())
        )
        + "\n"
    )


def main() -> int:
    expected = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            print("Frontend API types are stale. Run python scripts/export_client_types.py")
            return 1
    else:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
